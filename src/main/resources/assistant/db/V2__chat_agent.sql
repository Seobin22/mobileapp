    id BIGINT AUTO_INCREMENT PRIMARY KEY,
    title VARCHAR(500) NOT NULL,
    deadline TIMESTAMP WITH TIME ZONE,
    reason VARCHAR(4000) DEFAULT '' NOT NULL,
