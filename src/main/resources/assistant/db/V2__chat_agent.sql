-- start/end 는 blocks 와 같은 이유로 start_at/end_at
CREATE TABLE events(
    id BIGINT AUTO_INCREMENT PRIMARY KEY,
    title VARCHAR(500) NOT NULL,
    start_at TIMESTAMP WITH TIME ZONE NOT NULL,
    end_at TIMESTAMP WITH TIME ZONE NOT NULL,
    buffer_before_min INT DEFAULT 0 NOT NULL,
    buffer_after_min INT DEFAULT 0 NOT NULL,
    source VARCHAR(20) DEFAULT 'chat' NOT NULL,
    external_id VARCHAR(500),
    status VARCHAR(20) DEFAULT 'active' NOT NULL,
    sensitive BOOLEAN DEFAULT FALSE NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP NOT NULL
);

CREATE TABLE notes(
    id BIGINT AUTO_INCREMENT PRIMARY KEY,
    content VARCHAR(4000) NOT NULL,
    status VARCHAR(20) DEFAULT 'open' NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP NOT NULL
);

CREATE TABLE questions(
    id BIGINT AUTO_INCREMENT PRIMARY KEY,
    text VARCHAR(2000) NOT NULL,
    options VARCHAR(2000),
    status VARCHAR(20) DEFAULT 'open' NOT NULL,
    asked_at TIMESTAMP WITH TIME ZONE NOT NULL,
    answered_at TIMESTAMP WITH TIME ZONE
);

CREATE TABLE confirmations(
    id BIGINT AUTO_INCREMENT PRIMARY KEY,
    kind VARCHAR(30) NOT NULL,
    tool VARCHAR(50) NOT NULL,
    args VARCHAR(8000) NOT NULL,
    text VARCHAR(2000) NOT NULL,
    status VARCHAR(20) DEFAULT 'pending' NOT NULL,
    expires_at TIMESTAMP WITH TIME ZONE NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    resolved_at TIMESTAMP WITH TIME ZONE
);

CREATE TABLE messages(
    id BIGINT AUTO_INCREMENT PRIMARY KEY,
    role VARCHAR(20) NOT NULL,
    content VARCHAR(8000) NOT NULL,
    kind VARCHAR(20) NOT NULL,
    importance VARCHAR(10) DEFAULT 'normal' NOT NULL,
    silent BOOLEAN DEFAULT FALSE NOT NULL,
    question_id BIGINT REFERENCES questions(id),
    confirmation_id BIGINT REFERENCES confirmations(id),
    source VARCHAR(20),
    client_msg_id VARCHAR(100) UNIQUE,
    read_at TIMESTAMP WITH TIME ZONE,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE TABLE memory(
    id INT DEFAULT 1 PRIMARY KEY,
    content VARCHAR(20000) DEFAULT '' NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP NOT NULL
);
